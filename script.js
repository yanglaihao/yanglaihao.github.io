const root = document.documentElement;
const languageButton = document.querySelector("[data-language-toggle]");
const themeButton = document.querySelector("[data-theme-toggle]");
const menuButton = document.querySelector(".menu-toggle");
const navLinks = document.querySelector("[data-nav-links]");
const filters = document.querySelectorAll("[data-filter]");
const publications = document.querySelectorAll(".publication");
const bibDialog = document.querySelector("[data-bib-dialog]");
const bibOutput = document.querySelector("[data-bib-output]");
const copyBib = document.querySelector("[data-copy-bib]");

let currentLanguage = localStorage.getItem("language") || "zh";
let currentTheme = localStorage.getItem("theme") || "light";

function applyLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    element.textContent = translations[language][key] || element.textContent;
  });

  languageButton.textContent = language === "zh" ? "EN" : "中";
  localStorage.setItem("language", language);
}

function applyTheme(theme) {
  currentTheme = theme;
  root.dataset.theme = theme;
  localStorage.setItem("theme", theme);
}

languageButton.addEventListener("click", () => {
  applyLanguage(currentLanguage === "zh" ? "en" : "zh");
});

themeButton.addEventListener("click", () => {
  applyTheme(currentTheme === "light" ? "dark" : "light");
});

menuButton.addEventListener("click", () => {
  const isOpen = navLinks.classList.toggle("open");
  menuButton.setAttribute("aria-expanded", String(isOpen));
});

navLinks.addEventListener("click", (event) => {
  if (event.target instanceof HTMLAnchorElement) {
    navLinks.classList.remove("open");
    menuButton.setAttribute("aria-expanded", "false");
  }
});

filters.forEach((filter) => {
  filter.addEventListener("click", () => {
    const selected = filter.dataset.filter;
    filters.forEach((button) => button.classList.toggle("active", button === filter));

    publications.forEach((publication) => {
      publication.hidden = selected !== "all" && publication.dataset.type !== selected;
    });
  });
});

document.querySelectorAll("[data-bibtex]").forEach((button) => {
  button.addEventListener("click", () => {
    bibOutput.textContent = button.dataset.bibtex || "";
    bibDialog.showModal();
  });
});

async function writeToClipboard(text) {
  if (navigator.clipboard?.writeText) {
    await navigator.clipboard.writeText(text);
    return;
  }

  const scratch = document.createElement("textarea");
  scratch.value = text;
  scratch.setAttribute("readonly", "");
  scratch.style.position = "fixed";
  scratch.style.opacity = "0";
  document.body.append(scratch);
  scratch.select();
  document.execCommand("copy");
  scratch.remove();
}

if (copyBib) {
  copyBib.addEventListener("click", async () => {
    await writeToClipboard(bibOutput.textContent);
    const original = copyBib.textContent;
    copyBib.textContent = currentLanguage === "zh" ? "已复制" : "Copied";
    window.setTimeout(() => {
      copyBib.textContent = original;
    }, 1200);
  });
}

applyTheme(currentTheme);
applyLanguage(currentLanguage);
